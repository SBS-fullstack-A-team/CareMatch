       on inquiry (status);

    create index idx_job_posting_status_region 
       on job_posting (status, sigungu, job_type);

    create index idx_job_posting_deadline 
       on job_posting (deadline);

    create index idx_job_posting_draft_facility 
       on job_posting_draft (facility_profile_id);

    create index idx_refresh_token_member 
       on refresh_token (member_id);

    create index idx_terms_agreement_member 
       on terms_agreement (member_id, terms_type);

    create index idx_verification_target 
       on verification_code (channel, target);

