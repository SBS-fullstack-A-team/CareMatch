--     --spring.main.web-application-type=none \
--     --spring.jpa.properties.jakarta.persistence.schema-generation.scripts.action=create \
--     --spring.jpa.properties.jakarta.persistence.schema-generation.scripts.create-target=build/schema-postgres.sql \
--     --spring.jpa.properties.hibernate.dialect=org.hibernate.dialect.PostgreSQLDialect \
--     --spring.jpa.properties.hibernate.temp.use_jdbc_metadata_defaults=false \
--     --spring.jpa.hibernate.ddl-auto=none"
--   (bootRun 은 web-application-type=none 이라 컨텍스트 기동 후 non-zero 로 종료됨 — 정상.
--    스크립트는 EntityManagerFactory 초기화 시점에 build/schema-postgres.sql 로 기록됨)
--
-- 용도: prod DB 최초 프로비저닝 시 1회 실행. 자세한 절차는 docs/MIGRATION.md 참고.
-- 생성 기준: 아래 커밋의 엔티티 상태.
--
-- 참고: faq.answer / inquiry.content / inquiry_reply.content / notice.content /
--       terms.content 5개 컬럼은 @Lob 제거(→ @Column TEXT) 반영을 위해 재생성 없이
--       oid → text 로 직접 수정함. 다음 재생성 시 동일하게 text 로 나온다.
